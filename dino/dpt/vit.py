def _make_pretrained_dinov2_vitb14(
    name="dinov2_vitb14_reg",
    use_readout="project",
    hooks=None,
):
    """DINOv2-B 编码器 + 与 DPT-Large 相同的读出/通道配置.

    通道宽度沿用 DPT-Large 的 ``[256, 512, 1024, 1024]`` (而非 DPT-Base 的
    ``[96,192,384,768]``), 这样 DPT-Up2 的解码器 (refinenet / up_blocks /
    light_conv) 与 ViT-L 版本逐层同构, 只是读出投影的输入维度由 1024 变 768。
    """
    model = load_dinov2(name)
    hooks = [2, 5, 8, 11] if hooks is None else list(hooks)

    pretrained = _make_vit_b16_backbone(
        model,
        features=[256, 512, 1024, 1024],
        size=[518, 518],
        hooks=hooks,
        vit_features=DINOV2_B_DIM,
        use_readout=use_readout,
    )
    # _make_vit_b16_backbone 会把 patch_size 改成 timm 风格的 [16,16]; DINOv2
    # 内部需要整数 patch_size, 因此这里还原, 并把 DPT 侧需要的 (ph,pw) 单独存。
    pretrained.model.patch_size = DINOV2_B_PATCH
    pretrained.dinov2_patch = (DINOV2_B_PATCH, DINOV2_B_PATCH)
    pretrained.is_dinov2 = True
    pretrained.dinov2_hooks = tuple(hooks)
    return pretrained


